function result = make_result(name)
% MAKE_RESULT  Return a standard test result struct.
% Usage:
%   result = make_result('test_foo');
%   ... run tests ...
%   result.passed = true;   % or false
%   result.details = 'summary string';
result = struct( ...
    'passed',  false, ...
    'name',    name, ...
    'details', '', ...
    'subtests', struct('name', {}, 'passed', {}, 'msg', {}) ...
);
end
